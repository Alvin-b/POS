CREATE OR REPLACE FUNCTION public.update_butchery_category_price(
  _shop uuid,
  _category text,
  _price_per_kg_ksh integer
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_updated integer;
  v_price integer := greatest(1, _price_per_kg_ksh);
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not_authenticated';
  END IF;
  IF NOT public.is_platform_admin() AND NOT EXISTS (
    SELECT 1 FROM public.shop_members m
    WHERE m.shop_id = _shop
      AND m.user_id = auth.uid()
      AND m.role IN ('owner', 'manager')
      AND coalesce(m.employment_status, 'active') = 'active'
  ) THEN
    RAISE EXCEPTION 'Only an active owner or manager can update category prices.';
  END IF;

  UPDATE public.butchery_cuts
  SET price_per_kg_ksh = v_price,
      updated_at = now()
  WHERE shop_id = _shop
    AND lower(category) = lower(btrim(_category));

  GET DIAGNOSTICS v_updated = ROW_COUNT;

  IF lower(btrim(_category)) = 'beef' THEN
    UPDATE public.butchery_config
    SET default_beef_price_per_kg_ksh = v_price,
        updated_at = now()
    WHERE shop_id = _shop;
  END IF;

  RETURN coalesce(v_updated, 0);
END $$;

REVOKE ALL ON FUNCTION public.update_butchery_category_price(uuid, text, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.update_butchery_category_price(uuid, text, integer) TO authenticated;

CREATE OR REPLACE FUNCTION public.record_butchery_sale(
  _shop uuid,
  _cut_id text,
  _weight_grams integer,
  _total_ksh integer,
  _payment_method text,
  _entry_mode text,
  _operation_id uuid,
  _attendant_name text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_existing record;
  v_cut record;
  v_deduct integer;
  v_sale_id bigint;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not_authenticated';
  END IF;
  IF NOT public.is_platform_admin() AND NOT EXISTS (
    SELECT 1 FROM public.shop_members m
    WHERE m.shop_id = _shop
      AND m.user_id = auth.uid()
      AND coalesce(m.employment_status, 'active') = 'active'
  ) THEN
    RAISE EXCEPTION 'Only active business members can record Butchery sales.';
  END IF;

  IF coalesce(_weight_grams, 0) <= 0 OR coalesce(_total_ksh, 0) <= 0 THEN
    RAISE EXCEPTION 'Weight and total amount must be greater than zero.';
  END IF;

  IF _operation_id IS NOT NULL THEN
    SELECT id INTO v_existing
    FROM public.butchery_sales
    WHERE shop_id = _shop AND operation_id = _operation_id;
    IF FOUND THEN
      RETURN jsonb_build_object('success', true, 'id', v_existing.id, 'deduplicated', true);
    END IF;
  END IF;

  SELECT id, name, category, price_per_kg_ksh, stock_grams
  INTO v_cut
  FROM public.butchery_cuts
  WHERE id = _cut_id AND shop_id = _shop
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Meat cut not found.';
  END IF;

  v_deduct := CASE
    WHEN v_cut.stock_grams > 0 THEN least(v_cut.stock_grams, _weight_grams)
    ELSE 0
  END;

  IF v_deduct > 0 THEN
    UPDATE public.butchery_cuts
    SET stock_grams = greatest(0, stock_grams - v_deduct),
        updated_at = now()
    WHERE id = _cut_id AND shop_id = _shop;
  END IF;

  INSERT INTO public.butchery_sales (
    shop_id, operation_id, cut_id, cut_name, category, price_per_kg_ksh,
    weight_grams, total_ksh, payment_method, entry_mode,
    stock_deducted_grams, attendant_user_id, attendant_name
  )
  VALUES (
    _shop,
    _operation_id,
    v_cut.id,
    v_cut.name,
    v_cut.category,
    v_cut.price_per_kg_ksh,
    _weight_grams,
    _total_ksh,
    coalesce(nullif(btrim(_payment_method), ''), 'cash'),
    coalesce(nullif(btrim(_entry_mode), ''), 'amount'),
    v_deduct,
    auth.uid(),
    nullif(btrim(coalesce(_attendant_name, '')), '')
  )
  RETURNING id INTO v_sale_id;

  RETURN jsonb_build_object('success', true, 'id', v_sale_id);
END $$;

REVOKE ALL ON FUNCTION public.record_butchery_sale(uuid, text, integer, integer, text, text, uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_butchery_sale(uuid, text, integer, integer, text, text, uuid, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.undo_latest_butchery_sale(
  _shop uuid,
  _sale_id bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_sale record;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not_authenticated';
  END IF;
  IF NOT public.is_platform_admin() AND NOT EXISTS (
    SELECT 1 FROM public.shop_members m
    WHERE m.shop_id = _shop
      AND m.user_id = auth.uid()
      AND coalesce(m.employment_status, 'active') = 'active'
  ) THEN
    RAISE EXCEPTION 'forbidden';
  END IF;

  SELECT id, cut_id, stock_deducted_grams
  INTO v_sale
  FROM public.butchery_sales
  WHERE shop_id = _shop
    AND undone = false
    AND (_sale_id IS NULL OR id = _sale_id)
  ORDER BY created_at DESC, id DESC
  LIMIT 1
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'undone', false);
  END IF;

  UPDATE public.butchery_sales
  SET undone = true,
      undone_at = now()
  WHERE id = v_sale.id;

  IF coalesce(v_sale.stock_deducted_grams, 0) > 0 THEN
    UPDATE public.butchery_cuts
    SET stock_grams = stock_grams + v_sale.stock_deducted_grams,
        updated_at = now()
    WHERE id = v_sale.cut_id AND shop_id = _shop;
  END IF;

  RETURN jsonb_build_object('success', true, 'undone', true, 'sale_id', v_sale.id);
END $$;

REVOKE ALL ON FUNCTION public.undo_latest_butchery_sale(uuid, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.undo_latest_butchery_sale(uuid, bigint) TO authenticated;

