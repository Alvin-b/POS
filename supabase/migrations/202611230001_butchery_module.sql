-- Butchery Module tables, RLS policies, realtime publication, and SECURITY DEFINER RPCs.
-- Matches CounterPosRepository & SupabaseRestClient contracts.

CREATE TABLE IF NOT EXISTS public.butchery_config (
  shop_id uuid PRIMARY KEY REFERENCES public.shops(id) ON DELETE CASCADE,
  enabled boolean NOT NULL DEFAULT false,
  butchery_name text NOT NULL DEFAULT '',
  beef_only_mode boolean NOT NULL DEFAULT false,
  default_beef_price_per_kg_ksh integer NOT NULL DEFAULT 680 CHECK (default_beef_price_per_kg_ksh BETWEEN 50 AND 10000),
  payment_methods jsonb NOT NULL DEFAULT '["M-Pesa","Cash Payment"]'::jsonb,
  enabled_categories jsonb NOT NULL DEFAULT '["Beef","Goat/Mbuzi","Chicken","Liver/Matumbo","Pork"]'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.butchery_cuts (
  id text PRIMARY KEY,
  shop_id uuid NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
  name text NOT NULL,
  category text NOT NULL,
  price_per_kg_ksh integer NOT NULL CHECK (price_per_kg_ksh > 0),
  stock_grams integer NOT NULL DEFAULT 0 CHECK (stock_grams >= 0),
  icon_key text NOT NULL DEFAULT 'beef',
  active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS butchery_cuts_shop_sort_idx
  ON public.butchery_cuts (shop_id, sort_order, name);
CREATE INDEX IF NOT EXISTS butchery_cuts_shop_active_idx
  ON public.butchery_cuts (shop_id, active);

CREATE TABLE IF NOT EXISTS public.butchery_sales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id uuid NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
  operation_id uuid,
  cut_id text NOT NULL,
  cut_name text NOT NULL,
  category text NOT NULL,
  price_per_kg_ksh integer NOT NULL CHECK (price_per_kg_ksh > 0),
  weight_grams integer NOT NULL CHECK (weight_grams > 0),
  total_ksh integer NOT NULL CHECK (total_ksh > 0),
  payment_method text NOT NULL DEFAULT 'cash',
  entry_mode text NOT NULL DEFAULT 'amount',
  stock_deducted_grams integer NOT NULL DEFAULT 0,
  attendant_user_id uuid,
  attendant_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  undone boolean NOT NULL DEFAULT false,
  undone_at timestamptz,
  UNIQUE (shop_id, operation_id)
);

CREATE INDEX IF NOT EXISTS butchery_sales_shop_created_idx
  ON public.butchery_sales (shop_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS butchery_sales_shop_undone_created_idx
  ON public.butchery_sales (shop_id, undone, created_at DESC);

